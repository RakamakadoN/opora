import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const configPath = path.join(rootDir, 'data', 'kz-google-places.config.json');
const jsonOutputPath = path.join(rootDir, 'data', 'kz-google-places.generated.json');
const tsOutputPath = path.join(rootDir, 'src', 'data', 'kz-google-places.generated.ts');
const apiKey = process.env.GOOGLE_MAPS_API_KEY;

if (!apiKey) {
  throw new Error('GOOGLE_MAPS_API_KEY is required. Enable Places API (New) and run: GOOGLE_MAPS_API_KEY=... npm run update:kz-google-places');
}

const config = JSON.parse(await readFile(configPath, 'utf8'));
const today = new Date().toISOString().slice(0, 10);
const fieldMask = [
  'places.id',
  'places.displayName',
  'places.formattedAddress',
  'places.nationalPhoneNumber',
  'places.internationalPhoneNumber',
  'places.websiteUri',
  'places.googleMapsUri',
  'places.businessStatus',
  'places.rating',
  'places.userRatingCount',
  'places.types',
  'places.location',
  'nextPageToken'
].join(',');

const normalizeText = (value) => String(value || '').replace(/\s+/g, ' ').trim();
const sleep = (ms) => new Promise(resolve => setTimeout(resolve, ms));

const searchPlaces = async (textQuery) => {
  const response = await fetch('https://places.googleapis.com/v1/places:searchText', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-Goog-Api-Key': apiKey,
      'X-Goog-FieldMask': fieldMask
    },
    body: JSON.stringify({
      textQuery,
      languageCode: config.languageCode || 'ru',
      regionCode: config.country || 'KZ',
      pageSize: config.pageSize || 10
    })
  });

  if (!response.ok) {
    const text = await response.text().catch(() => '');
    throw new Error(`Google Places failed for "${textQuery}": ${response.status} ${text}`);
  }

  const data = await response.json();
  return Array.isArray(data.places) ? data.places : [];
};

const getPlaceName = (place) => normalizeText(place.displayName?.text);
const placeKey = (place) => `${place.id || getPlaceName(place)}|${place.formattedAddress || ''}`.toLowerCase();

const allResults = [];

for (const city of config.cities) {
  for (const query of config.queries) {
    const textQuery = query.text.replace('{city}', city);
    console.log(`Searching: ${textQuery}`);
    const places = await searchPlaces(textQuery);
    for (const place of places) {
      allResults.push({ city, query, place });
    }
    await sleep(250);
  }
}

const seen = new Set();
const items = [];

for (const result of allResults) {
  const { city, query, place } = result;
  const name = getPlaceName(place);
  const address = normalizeText(place.formattedAddress);
  if (!name || !address) continue;

  const key = placeKey(place);
  if (seen.has(key)) continue;
  seen.add(key);

  items.push({
    id: 800000 + items.length + 1,
    placeId: place.id,
    name,
    city,
    title: 'Кандидат из Google Places',
    desc: 'Найдено через Google Places по запросам РАС/аутизм/ABA. Это не рекомендация и не подтверждение качества. Нужно проверить администратором и родителями: опыт с РАС, сенсорная бережность, подход к неговорящим детям, реальные отзывы семей.',
    address,
    website: place.websiteUri,
    sourceUrl: place.googleMapsUri,
    sourceLabel: 'Google Places · требует проверки родителей',
    lastVerified: today,
    verificationStatus: 'needs_review',
    tags: [...new Set([...(query.tags || []), city])],
    type: 'center',
    rating: Number(place.rating || 0),
    ratingCount: Number(place.userRatingCount || 0),
    phone: normalizeText(place.nationalPhoneNumber || place.internationalPhoneNumber || 'Контакт уточнить'),
    country: 'KZ',
    confidenceScore: 0.45,
    reviews: []
  });
}

const payload = {
  generatedAt: today,
  source: 'google_places_text_search',
  note: 'Candidates from Google Places API. Review manually and validate with parent experience before recommendation.',
  items
};

const generated = `// Generated by scripts/update-kz-google-places.mjs. Do not edit by hand.
// Google Places data must be reviewed by parents/admins before recommendation.
export const KZ_GOOGLE_PLACES_ITEMS = ${JSON.stringify(items, null, 2)} as const;
`;

await mkdir(path.dirname(jsonOutputPath), { recursive: true });
await writeFile(jsonOutputPath, JSON.stringify(payload, null, 2), 'utf8');
await writeFile(tsOutputPath, generated, 'utf8');

console.log(`Generated ${items.length} Kazakhstan Google Places candidates.`);
console.log(`JSON: ${path.relative(rootDir, jsonOutputPath)}`);
console.log(`TS: ${path.relative(rootDir, tsOutputPath)}`);

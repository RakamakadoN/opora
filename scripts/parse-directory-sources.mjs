import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(rootDir, 'data', 'directory-sources.json');
const outputPath = path.join(rootDir, 'src', 'data', 'directory.generated.ts');

const required = ['id', 'name', 'city', 'address', 'phone', 'type', 'tags'];
const validTypes = new Set(['doctor', 'center', 'org', 'gov', 'friendly']);

const source = JSON.parse(await readFile(sourcePath, 'utf8'));

const normalizeText = (value) => String(value || '').replace(/\s+/g, ' ').trim();

const normalizeItem = (item, sourceInfo) => {
  for (const field of required) {
    if (item[field] === undefined || item[field] === null || item[field] === '') {
      throw new Error(`Missing field "${field}" for item ${item.id || item.name}`);
    }
  }

  if (!validTypes.has(item.type)) {
    throw new Error(`Invalid type "${item.type}" for item ${item.id}`);
  }

  return {
    id: Number(item.id),
    name: normalizeText(item.name),
    city: normalizeText(item.city),
    title: item.title ? normalizeText(item.title) : undefined,
    desc: normalizeText(
      item.note ||
        `Официально указанное учреждение. Адрес: ${item.address}.${item.email ? ` Email: ${item.email}.` : ''}`
    ),
    address: normalizeText(item.address),
    website: item.website || sourceInfo.url,
    sourceUrl: item.website || sourceInfo.url,
    sourceLabel: sourceInfo.label,
    lastVerified: source.generatedAt,
    verificationStatus: item.verificationStatus || sourceInfo.verificationStatus || 'verified',
    tags: [...new Set((item.tags || []).map(normalizeText).filter(Boolean))],
    type: item.type,
    rating: 0,
    ratingCount: 0,
    phone: normalizeText(item.phone),
    reviews: []
  };
};

const allItems = source.sources.flatMap((sourceInfo) =>
  sourceInfo.items.map((item) => normalizeItem(item, sourceInfo))
);

const seen = new Set();
const uniqueItems = allItems.filter((item) => {
  const key = `${item.name.toLowerCase()}|${item.city.toLowerCase()}`;
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

const generated = `// Generated by scripts/parse-directory-sources.mjs. Do not edit by hand.
export const VERIFIED_DIRECTORY_ITEMS = ${JSON.stringify(uniqueItems, null, 2)} as const;
`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated, 'utf8');

console.log(`Generated ${uniqueItems.length} directory items -> ${path.relative(rootDir, outputPath)}`);
